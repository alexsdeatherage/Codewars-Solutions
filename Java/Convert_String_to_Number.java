// Input: "0" -> Output: 0 
// Input: "2" -> Output: 2 
// Input: "-2" -> Output: -2 

public class StringToNumber {
  public static int stringToNumber(String str) {
    // take str variable, and turn it into a number using a built-int function
    return Integer.parseInt(str);
    // assign the new number to a variable, and return it
  }
}